.section .text
.globl _start
_start:
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
#Carga el registro ra en puros 1 y el registro sp con puros 0
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
li ra,0xFFFFFFFF
li sp,0x00000000
li a7,0x01010101
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
#Escribe este contenido en los CSR.
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
csrrw x0,0,a7
csrrw x0,1,a7
csrrw x0,2,a7
csrrw x0,3,a7
csrrw x0,4,a7
csrrw x0,5,a7
csrrw x0,6,a7
csrrw x0,7,a7
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
#Ahora se prueba la instruccion variando su operacion con ra y sp.
#-------------------------------------------------------------------------------
#-------------------------------------------------------------------------------
csrrc s0,0,ra
csrrc s1,1,sp
csrrc a0,2,ra
csrrc a1,3,sp
csrrc a2,4,ra
csrrc a3,5,sp
csrrc a4,6,ra
csrrc a5,7,sp
